#!/usr/bin/env python3
"""Regenerate everything derived from `spec/openapi.public.json` — one command, idempotent (CI runs it and then
`git diff --exit-code`):

1. `src/tasksmate/_generated/`  openapi-python-client 0.29.1 (config `openapi-python-client.yaml`; two one-line
                                template overrides in `templates/`: a model `etag` field, `Self` from typing_extensions
                                for Python 3.10), a do-not-edit header on every file, `ruff format`;
2. `src/tasksmate/_operations.py`  the facade's operation table: method, path, parameters, filters, body, list /
                                create / If-Match / If-None-Match, scopes — and each operation's generated parser;
3. `src/tasksmate/resources.py`  `tm.<resource>.<verb>(…)` for every public operationId (sync and async), typed with
                                the generated models;
4. `docs/api/*.md`              one Markdown page per resource from the spec's summaries (4.6 renders them).

Nothing here calls the network. Usage: `python scripts/generate.py` (from the repo root, dev extras installed).
"""

from __future__ import annotations

import json
import keyword
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "openapi.public.json"
PKG = ROOT / "src" / "tasksmate"
GEN = PKG / "_generated"
DOCS = ROOT / "docs" / "api"
GENERATOR_VERSION = "0.29.1"
HEADER = (
    "# GENERATED by scripts/generate.py from spec/openapi.public.json — DO NOT EDIT BY HAND.\n"
    "# Change the spec snapshot (or the generator) and run `python scripts/generate.py`.\n"
)

# 4.1b: these used to leak from the backend's `verify_token` signature onto every operation and were dropped here;
# the backend no longer declares them, and generation now refuses a spec that does (they would become method arguments).
LEAKED = {"is_registration", "authorization"}
# Friendlier names on top of the operationId verbs (the verbs stay; these are aliases).
ALIASES = {"tasks": {"move": "set_project"}}


def bin_(name: str) -> str:
    return str(Path(sys.executable).parent / name)


def run(*cmd: str, cwd: Path = ROOT) -> None:
    subprocess.run(list(cmd), cwd=cwd, check=True)


# ---------------------------------------------------------------------------
# 1. the generated client
# ---------------------------------------------------------------------------


def check_spec(spec: dict[str, Any]) -> None:
    """Refuse a spec with the defects 4.1b fixed at the source, instead of patching around them again:
    - an update body (PATCH / PUT) whose schema advertises a `default`: every update route writes only what the body
      set, so the server never applies it — but a generated model sends a default as though the caller had set it
      (`TaskUpdate(status=...)` also reset priority and type; 4.5 stripped the defaults here until 4.1b);
    - `authorization` / `is_registration` declared as operation parameters."""
    problems = []
    schemas = spec["components"]["schemas"]
    for path, item in spec["paths"].items():
        for method, op in item.items():
            where = f"{method.upper()} {path}"
            problems += [f"{where}: parameter {p['name']}" for p in op.get("parameters", []) if p["name"] in LEAKED]
            if method not in ("patch", "put"):
                continue
            for body in op.get("requestBody", {}).get("content", {}).values():
                name = body.get("schema", {}).get("$ref", "").rsplit("/", 1)[-1]
                for prop, sub in schemas.get(name, {}).get("properties", {}).items():
                    if sub.get("default") is not None:
                        problems.append(f"{where}: {name}.{prop} has default {sub['default']!r}")
    if problems:
        sys.exit(
            "the spec regressed on 4.1b (fix the backend, not the generator):\n  " + "\n  ".join(sorted(set(problems)))
        )


def generate_client(spec: dict[str, Any]) -> None:
    clash = [name for name, schema in spec["components"]["schemas"].items() if "etag" in schema.get("properties", {})]
    if clash:  # the model template adds a non-serialized `etag` field to every model
        sys.exit(f"schemas with an `etag` property would clash with the facade's etag field: {clash}")
    version = subprocess.run(
        [bin_("openapi-python-client"), "--version"], capture_output=True, text=True, check=True
    ).stdout
    if GENERATOR_VERSION not in version:
        sys.exit(
            f"openapi-python-client {GENERATOR_VERSION} is required (found: {version.strip()}); pip install -e '.[dev]'"
        )
    if GEN.exists():
        shutil.rmtree(GEN)
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp) / "openapi.public.json"
        source.write_text(json.dumps(spec, indent=2))
        run(
            bin_("openapi-python-client"),
            "generate",
            "--path",
            str(source),
            "--output-path",
            str(GEN),
            "--meta",
            "none",
            "--config",
            str(ROOT / "openapi-python-client.yaml"),
            "--custom-template-path",
            str(ROOT / "templates"),
            "--overwrite",
        )
    for path in sorted(GEN.rglob("*.py")):
        path.write_text(HEADER + path.read_text())
    run(bin_("ruff"), "format", "--quiet", "--no-respect-gitignore", "--config", "line-length=120", str(GEN))


# ---------------------------------------------------------------------------
# 2–3. the facade
# ---------------------------------------------------------------------------


def norm(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower())


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]+", name) if part)


def py_name(name: str) -> str:
    name = re.sub(r"[^0-9A-Za-z_]", "_", name)
    return name + "_" if keyword.iskeyword(name) or name in {"filter", "body"} else name


def model_classes() -> dict[str, str]:
    """normalized component name → generated class name (and literal enums)."""
    found: dict[str, str] = {}
    for path in sorted((GEN / "models").glob("*.py")):
        for match in re.finditer(r"^class (\w+)\b|^(\w+) = Literal\[", path.read_text(), re.M):
            name = match.group(1) or match.group(2)
            found.setdefault(norm(name), name)
    return found


def generated_modules() -> dict[str, str]:
    """ "METHOD /path" → "tag_dir.module" from each generated module's `_get_kwargs`."""
    out: dict[str, str] = {}
    for path in sorted((GEN / "api").glob("*/*.py")):
        match = re.search(r'"method":\s*"(\w+)",\s*"url":\s*"([^"]+)"', path.read_text())
        if match:
            out[f"{match.group(1).upper()} {match.group(2)}"] = f"{path.parent.name}.{path.stem}"
    return out


@dataclass
class Param:
    wire: str
    py: str
    annotation: str
    required: bool
    description: str = ""


@dataclass
class Op:
    op_id: str
    resource: str
    verb: str
    method: str
    path: str
    summary: str
    description: str
    scopes: list[str]
    module: str
    path_params: list[str] = field(default_factory=list)
    query: list[Param] = field(default_factory=list)
    filters: list[str] = field(default_factory=list)
    body: str | None = None
    body_model: str | None = None
    body_required: bool = False
    form: list[Param] = field(default_factory=list)
    files: list[str] = field(default_factory=list)
    is_list: bool = False
    is_create: bool = False
    if_match: bool = False
    if_none_match: bool = False
    returns: str = "model"
    return_type: str = "None"
    item: str | None = None


class Facade:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, Any] = spec["components"]["schemas"]
        self.classes = model_classes()
        self.modules = generated_modules()
        self.ops: list[Op] = []
        self.tag_text = {t["name"]: t.get("description", "") for t in spec.get("tags", [])}

    def cls(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        found = self.classes.get(norm(name))
        if not found:
            sys.exit(f"no generated class for schema {name}")
        return found

    def schema(self, ref: str) -> dict[str, Any]:
        return dict(self.schemas[ref.rsplit("/", 1)[-1]])

    def envelope_item(self, ref: str) -> str | None:
        """The item class when `ref` is a `{data: [...], next_cursor}` envelope, else None."""
        props = self.schema(ref).get("properties", {})
        if "data" not in props or "next_cursor" not in props or props["data"].get("type") != "array":
            return None
        items = props["data"].get("items", {})
        if "$ref" in items:
            return self.cls(items["$ref"])
        module = GEN / "models" / (re.sub(r"(?<!^)(?=[A-Z])", "_", self.cls(ref)).lower() + ".py")
        match = re.search(r"^\s+data: list\[(\w+)\]", module.read_text(), re.M) if module.exists() else None
        return match.group(1) if match else None

    @staticmethod
    def annotation(schema: dict[str, Any]) -> str:
        options = [s for s in schema.get("anyOf", [schema]) if s.get("type") != "null"]
        kind = options[0].get("type") if options else None
        if kind == "array":
            return "Sequence[str]"
        return {"integer": "int", "boolean": "bool", "number": "float"}.get(str(kind), "str")

    def build(self) -> None:
        for path, item in self.spec["paths"].items():
            for method, raw in item.items():
                self.ops.append(self.operation(path, method.upper(), raw))

    def operation(self, path: str, method: str, raw: dict[str, Any]) -> Op:
        op_id = raw["operationId"]
        resource, verb = op_id.split(".", 1)
        key = f"{method} {path}"
        if key not in self.modules:
            sys.exit(f"no generated module for {key}")
        op = Op(
            op_id,
            resource,
            verb,
            method,
            path,
            raw.get("summary", ""),
            raw.get("description", ""),
            list(raw.get("x-scopes", [])),
            self.modules[key],
        )
        # 4.1b: the spec says which operations are lists / creates (`x-kind`, from the backend's surface table)
        kind = raw.get("x-kind", "")
        op.is_create = kind == "create"
        for prm in raw.get("parameters", []):
            name, where = prm["name"], prm["in"]
            if where == "path":
                op.path_params.append(name)
            elif where == "header":
                op.if_match |= name == "If-Match"
                op.if_none_match |= name == "If-None-Match"
            elif name.startswith("filter["):
                op.filters.append(name[len("filter[") : -1])
            elif prm.get("deprecated") or (prm.get("description") or "").lower().startswith("deprecated"):
                continue
            else:
                op.query.append(
                    Param(
                        name,
                        py_name(name),
                        self.annotation(prm.get("schema", {})),
                        bool(prm.get("required")),
                        (prm.get("description") or "").split("\n")[0],
                    )
                )
        in_path = re.findall(r"\{(\w+)\}", path)
        op.path_params.sort(key=in_path.index)
        body = raw.get("requestBody")
        if body:
            content = body.get("content", {})
            op.body_required = bool(body.get("required"))
            if "application/json" in content:
                op.body = "json"
                op.body_model = self.cls(content["application/json"]["schema"]["$ref"])
            else:
                op.body = "multipart"
                schema = self.schema(next(iter(content.values()))["schema"]["$ref"])
                required = set(schema.get("required", []))
                for name, prop in schema["properties"].items():
                    if prop.get("contentMediaType") or prop.get("format") == "binary":
                        op.files.append(name)
                        op.form.append(Param(name, py_name(name), "FileInput", name in required))
                    else:
                        op.form.append(Param(name, py_name(name), self.annotation(prop), name in required))
        self.response(op, raw, kind == "list")
        if op.is_create and not any(p["name"] == "Idempotency-Key" for p in raw.get("parameters", [])):
            sys.exit(f"{op_id}: x-kind create without an Idempotency-Key parameter")
        if kind == "list" and not op.is_list:
            sys.exit(f"{op_id}: x-kind list without a {{data, next_cursor}} envelope")
        if op.is_list:
            op.if_none_match = (
                False  # a page is re-read, not revalidated: the facade offers If-None-Match on single reads
            )
        return op

    def response(self, op: Op, raw: dict[str, Any], is_list: bool) -> None:
        status = next((s for s in raw["responses"] if s.startswith("2")), None)
        content = raw["responses"].get(status or "", {}).get("content") or {}
        if not content or status == "204":
            op.returns, op.return_type = "none", "None"
            return
        schema = content.get("application/json", {}).get("schema")
        if schema is None:
            op.returns, op.return_type = "text", "str"
            return
        members = schema.get("anyOf") if "anyOf" in schema else [schema]
        types: list[str] = []
        for member in members:
            if member.get("type") == "array":
                types.append(f"builtins.list[models.{self.cls(member['items']['$ref'])}]")
                continue
            item = self.envelope_item(member["$ref"]) if is_list else None
            if item:
                op.is_list, op.item = True, item
                types.append(f"Page[models.{item}]")
            else:
                types.append(f"models.{self.cls(member['$ref'])}")
        op.return_type = " | ".join(types)

    # -- emit: operations table ------------------------------------------------------------------------------

    def emit_operations(self) -> str:
        imports = sorted({op.module for op in self.ops})
        items = sorted({op.item for op in self.ops if op.item})
        lines = [
            HEADER,
            '"""The public operations, generated from `spec/openapi.public.json` (see scripts/generate.py)."""',
            "from __future__ import annotations",
            "",
            "from ._core import Operation",
        ]
        for module in imports:
            tag, name = module.split(".")
            lines.append(f"from ._generated.api.{tag} import {name} as _{name}")
        lines.append(f"from ._generated.models import {', '.join(items)}")
        servers = self.spec.get("servers") or [{"url": "http://localhost:8000"}]
        lines += [
            "",
            f"API_VERSION = {self.spec['info']['version']!r}",
            '"""The API date of the spec this SDK was generated from (`info.version`)."""',
            f"DEFAULT_BASE_URL = {servers[0]['url']!r}",
            '"""The spec\'s first server — the base URL when neither `base_url=` nor TASKSMATE_API_URL is given."""',
            "",
            "OPERATIONS: dict[str, Operation] = {",
        ]
        for op in self.ops:
            fields = [f"op_id={op.op_id!r}", f"method={op.method!r}", f"path={op.path!r}"]
            if op.path_params:
                fields.append(f"path_params={tuple(op.path_params)!r}")
            if op.query:
                fields.append(f"query={tuple(p.wire for p in op.query)!r}")
            if op.filters:
                fields.append(f"filters={tuple(op.filters)!r}")
            if op.body:
                fields.append(f"body={op.body!r}")
            if op.files:
                fields.append(f"files={tuple(op.files)!r}")
            for flag in ("is_list", "is_create", "if_match", "if_none_match"):
                if getattr(op, flag):
                    fields.append(f"{flag}=True")
            if op.returns != "model":
                fields.append(f"returns={op.returns!r}")
            fields.append(f"parse=_{op.module.split('.')[1]}._parse_response")
            if op.item:
                fields.append(f"item={op.item}.from_dict")
            if op.scopes:
                fields.append(f"scopes={tuple(op.scopes)!r}")
            fields.append(f"summary={op.summary!r}")
            lines.append(f"    {op.op_id!r}: Operation({', '.join(fields)}),")
        lines += ["}", ""]
        return "\n".join(lines)

    # -- emit: resources --------------------------------------------------------------------------------------

    def signature(self, op: Op, *, none_match: str | None = None) -> tuple[list[str], list[str]]:
        """(parameters after `self`, the `_call` keyword arguments)."""
        params: list[str] = [f"{p}: str" for p in op.path_params]
        call: list[str] = []
        if op.path_params:
            joined = ", ".join(op.path_params) + ("," if len(op.path_params) == 1 else "")
            call.append(f"path=({joined})")
        if op.body == "json":
            ann = f"models.{op.body_model} | Mapping[str, Any]"
            params.append(f"body: {ann}" if op.body_required else f"body: {ann} | None = None")
            call.append("body=body")
        kw: list[str] = []
        # A form field that is ALSO a query parameter (`project-resources.upload`'s `project_id`) is one argument,
        # sent in both places.
        query_names = {p.py for p in op.query}
        form_only = [p for p in op.form if p.py not in query_names]
        required = [p for p in op.query if p.required] + [p for p in form_only if p.required]
        optional = [p for p in op.query if not p.required] + [p for p in form_only if not p.required]
        kw += [f"{p.py}: {p.annotation}" for p in required]
        kw += [f"{p.py}: {p.annotation} | None = None" for p in optional]
        if op.query:
            call.append("query={" + ", ".join(f"{p.wire!r}: {p.py}" for p in op.query) + "}")
        if op.form:
            call.append("form={" + ", ".join(f"{p.wire!r}: {p.py}" for p in op.form) + "}")
        if op.filters:
            kw.append("filter: Mapping[str, Any] | None = None")
            call.append("filter=filter")
        if op.if_match:
            kw.append("if_match: str | None = None")
            call.append("if_match=if_match")
        if op.if_none_match:
            kw.append(none_match or "if_none_match: str | None = None")
            call.append("if_none_match=if_none_match")
        if op.is_create:
            kw.append("idempotency_key: str | _Auto | None = AUTO")
            call.append("idempotency_key=idempotency_key")
        if kw:
            params.append("*")
            params += kw
        return params, call

    def docstring(self, op: Op) -> str:
        bits = [f"`{op.method} {op.path}`"]
        if op.scopes:
            bits.append(f"scope `{op.scopes[0]}`")
        if op.is_list:
            bits.append("a `Page` — iterate it for every item")
        if op.filters:
            bits.append("filter keys: " + ", ".join(op.filters))
        if op.is_create:
            bits.append("`Idempotency-Key` sent automatically")
        if op.if_match:
            bits.append("`if_match=<etag>` → 412 when stale")
        if op.if_none_match:
            bits.append("`if_none_match=<etag>` → `NotModified` when unchanged")
        summary = op.summary.replace('"""', "'''").replace("\\", "\\\\")
        return f'"""{summary}.\n\n        ' + " · ".join(bits) + '\n        """'

    def emit_method(self, op: Op, name: str, is_async: bool) -> list[str]:
        params, call = self.signature(op)
        ret = op.return_type.replace("Page[", "AsyncPage[") if is_async else op.return_type
        defn = "async def" if is_async else "def"
        awaited = "await " if is_async else ""
        target = "_call"
        body_call = f"self._client.{target}(_OPS[{op.op_id!r}]{''.join(', ' + c for c in call)})"
        lines: list[str] = []
        if op.if_none_match:
            p1, _ = self.signature(op, none_match="if_none_match: None = None")
            p2, _ = self.signature(op, none_match="if_none_match: str")
            lines += [
                "    @overload",
                f"    {defn} {name}(self, {', '.join(p1)}) -> {ret}: ...",
                "    @overload",
                f"    {defn} {name}(self, {', '.join(p2)}) -> {ret} | NotModifiedType: ...",
            ]
            ret = f"{ret} | NotModifiedType"
        joined = ", ".join(["self", *params])
        lines += [
            f"    {defn} {name}({joined}) -> {ret}:",
            f"        {self.docstring(op)}",
            f"        return cast({ret!r}, {awaited}{body_call})",
            "",
        ]
        return lines

    def resources(self) -> dict[str, list[Op]]:
        grouped: dict[str, list[Op]] = {}
        for op in self.ops:
            grouped.setdefault(op.resource, []).append(op)
        return grouped

    def emit_resources(self) -> str:
        out = [
            HEADER,
            '"""`tm.<resource>.<verb>(…)` — one method per public operationId (scripts/generate.py)."""',
            "from __future__ import annotations",
            "",
            "import builtins",
            "from collections.abc import Mapping, Sequence",
            "from typing import Any, cast, overload",
            "",
            "from ._core import AUTO, AsyncCore, FileInput, NotModifiedType, SyncCore, _Auto",
            "from ._generated import models",
            "from ._operations import OPERATIONS as _OPS",
            "from .pagination import AsyncPage, Page",
            "",
            "__all__ = ['AsyncResources', 'SyncResources', 'RESOURCE_METHODS']",
            "",
            "",
        ]
        grouped = self.resources()
        for is_async in (False, True):
            for resource, ops in grouped.items():
                cls = ("Async" if is_async else "") + pascal(resource) + "Resource"
                text = self.tag_text.get(resource, "").replace('"""', "'''")
                out += [
                    f"class {cls}:",
                    f'    """{text}"""',
                    "",
                    f"    def __init__(self, client: {'AsyncCore' if is_async else 'SyncCore'}) -> None:",
                    "        self._client = client",
                    "",
                ]
                verbs = {op.verb for op in ops}
                for op in ops:
                    out += self.emit_method(op, op.verb, is_async)
                if "read" in verbs and "get" not in verbs:
                    out += ["    get = read", '    """Alias of `read`."""', ""]
                for alias, target in ALIASES.get(resource, {}).items():
                    if target in verbs:
                        out += [f"    {alias} = {target}", f'    """Alias of `{target}`."""', ""]
                if resource == "me":
                    out += ["    __call__ = read", '    """`tm.me()` is `tm.me.read()`."""', ""]
                out += [""]
        for is_async in (False, True):
            prefix = "Async" if is_async else ""
            core = "AsyncCore" if is_async else "SyncCore"
            out += [
                f"class {'AsyncResources' if is_async else 'SyncResources'}:",
                '    """Every resource namespace, attached to a client."""',
                "",
            ]
            for resource in grouped:
                out.append(f"    {py_name(resource)}: {prefix}{pascal(resource)}Resource")
            out += ["", f"    def _attach(self, core: {core}) -> None:"]
            for resource in grouped:
                out.append(f"        self.{py_name(resource)} = {prefix}{pascal(resource)}Resource(core)")
            out += ["", ""]
        mapping = ", ".join(f"{op.op_id!r}: ({py_name(op.resource)!r}, {op.verb!r})" for op in self.ops)
        out += [
            "RESOURCE_METHODS: dict[str, tuple[str, str]] = {" + mapping + "}",
            '"""operationId → (resource attribute, method) — `tests/test_drift.py` checks it covers the spec."""',
            "",
        ]
        return "\n".join(out)

    # -- emit: docs -------------------------------------------------------------------------------------------

    def emit_docs(self) -> dict[str, str]:
        pages: dict[str, str] = {}
        index = [
            "# API reference",
            "",
            "_Generated by `scripts/generate.py` from `spec/openapi.public.json` "
            f"(API version `{self.spec['info']['version']}`) — do not edit by hand._",
            "",
            "Every operation is `tm.<resource>.<method>(…)` on `TasksMate` (and `await` on `AsyncTasksMate`).",
            "",
            "| Resource | Operations | |",
            "|---|---|---|",
        ]
        for resource, ops in self.resources().items():
            attr = py_name(resource)
            index.append(f"| [`tm.{attr}`]({resource}.md) | {len(ops)} | {self.tag_text.get(resource, '')} |")
            lines = [
                f"# `tm.{attr}`",
                "",
                self.tag_text.get(resource, ""),
                "",
                "_Generated from `spec/openapi.public.json` by `scripts/generate.py` — do not edit by hand._",
                "",
            ]
            for op in ops:
                params, _ = self.signature(op)
                shown = ", ".join(p for p in params if p != "*").replace("models.", "").replace(" | _Auto", "")
                lines += [
                    f"## `tm.{attr}.{op.verb}({shown})`",
                    "",
                    f"{op.summary}.",
                    "",
                    f"- **HTTP:** `{op.method} {op.path}`",
                    f"- **operationId:** `{op.op_id}`",
                ]
                if op.scopes:
                    lines.append(f"- **Token scope:** `{op.scopes[0]}`")
                lines.append(f"- **Returns:** `{op.return_type.replace('builtins.', '').replace('models.', '')}`")
                if op.is_list:
                    lines.append("- **List:** returns a `Page`; iterating it follows `next_cursor` through every page.")
                if op.filters:
                    lines.append("- **`filter=` keys:** " + ", ".join(f"`{f}`" for f in op.filters))
                if op.is_create:
                    lines.append(
                        "- **Idempotent create:** an `Idempotency-Key` is sent (and reused by retries) unless "
                        "`idempotency_key=None`."
                    )
                if op.if_match:
                    lines.append(
                        "- **Conditional write:** `if_match=obj.etag` → `PreconditionFailedError` (412) when stale."
                    )
                if op.if_none_match:
                    lines.append("- **Conditional read:** `if_none_match=obj.etag` → `NotModified` when unchanged.")
                lines.append("")
            pages[f"{resource}.md"] = "\n".join(lines).rstrip() + "\n"
        pages["README.md"] = "\n".join(index) + "\n"
        return pages


def main() -> None:
    spec = json.loads(SPEC.read_text())
    check_spec(spec)
    generate_client(spec)
    facade = Facade(spec)
    facade.build()
    (PKG / "_operations.py").write_text(facade.emit_operations())
    (PKG / "resources.py").write_text(facade.emit_resources())
    if DOCS.exists():
        shutil.rmtree(DOCS)
    DOCS.mkdir(parents=True)
    for name, text in facade.emit_docs().items():
        (DOCS / name).write_text(text)
    targets = [str(PKG / "_operations.py"), str(PKG / "resources.py")]
    run(bin_("ruff"), "check", "--quiet", "--fix-only", *targets)
    run(bin_("ruff"), "format", "--quiet", *targets)
    lists = sum(op.is_list for op in facade.ops)
    creates = sum(op.is_create for op in facade.ops)
    print(
        f"generated: {len(facade.ops)} operations in {len(facade.resources())} resources "
        f"({lists} lists, {creates} idempotent creates), {len(list((GEN / 'models').glob('*.py')))} model modules, "
        f"API version {spec['info']['version']}"
    )


if __name__ == "__main__":
    main()
